import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { readTokenTexts } from '../cursor_ir/token_classes';
import { readGrammarLabels } from './read_grammar';

const LICENSE_HEADER = `/*
 * Copyright Elasticsearch B.V. and/or licensed to Elasticsearch B.V. under one
 * or more contributor license agreements. Licensed under the "Elastic License
 * 2.0", the "GNU Affero General Public License v3.0 only", and the "Server Side
 * Public License v 1"; you may not use this file except in compliance with, at
 * your election, the "Elastic License 2.0", the "GNU Affero General Public
 * License v3.0 only", or the "Server Side Public License, v 1".
 */`;

/** Writes `grammar_labels.generated.ts` from the installed grammar (Node only). */
export const writeGrammarLabels = (): string => {
  const target = resolve(__dirname, 'grammar_labels.generated.ts');
  writeFileSync(
    target,
    `${LICENSE_HEADER}

// Generated by scripts/generate_grammar_labels.js in @kbn/esql-language. Do not edit by hand.
import type { GrammarLabel } from './types';

export const GRAMMAR_LABELS: readonly GrammarLabel[] = ${JSON.stringify(
      readGrammarLabels(),
      null,
      2
    )};

/** The fixed text of each token that has one, lower-cased, by the name of the token. */
export const TOKEN_TEXTS: Readonly<Record<string, string>> = ${JSON.stringify(
      readTokenTexts(),
      null,
      2
    )};
`
  );
  return target;
};
